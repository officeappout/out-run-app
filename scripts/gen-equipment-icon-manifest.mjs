#!/usr/bin/env node
/**
 * gen-equipment-icon-manifest.mjs
 *
 * Writes a BUILD-TIME manifest of the equipment SVG assets that physically exist
 * in public/assets/icons/equipment/. The runtime (browser) resolver uses it to
 * check icon existence synchronously — no fs at runtime, no fetch, no
 * broken-image flicker — and, crucially, it lists EVERY file on disk, including
 * ones that are absent from the static ICON_KEY_TO_SVG table (e.g. the orphaned
 * training_steps.svg), which is exactly why an authored iconKey can now win.
 *
 * Wired to the predev/prebuild npm hooks so new icons are picked up automatically.
 * Defensive: never throws → can never break `next build`. Writes only on change.
 *
 * Usage: node scripts/gen-equipment-icon-manifest.mjs
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ICON_DIR = join(ROOT, 'public/assets/icons/equipment');
const OUT = join(ROOT, 'src/features/workout-engine/shared/utils/equipment-icon-manifest.ts');

try {
  if (!existsSync(ICON_DIR)) {
    console.warn('[gen-equipment-icons] icon dir missing — skipping (manifest left unchanged)');
    process.exit(0);
  }
  const files = readdirSync(ICON_DIR)
    .filter((f) => f.toLowerCase().endsWith('.svg'))
    .sort();

  const body =
    '// AUTO-GENERATED by scripts/gen-equipment-icon-manifest.mjs — DO NOT EDIT.\n' +
    '// Build-time list of the equipment SVG assets in public/assets/icons/equipment/.\n' +
    '// Refreshed by the predev/prebuild npm hooks. Consulted synchronously so an\n' +
    '// authored iconKey can win over the static canonical collapse without any\n' +
    '// runtime fs / fetch (no broken-image flicker). Includes files that are absent\n' +
    '// from ICON_KEY_TO_SVG (e.g. training_steps.svg), which is the whole point.\n' +
    'export const EQUIPMENT_ICON_FILES: ReadonlySet<string> = new Set([\n' +
    files.map((f) => `  '${f}',`).join('\n') +
    '\n]);\n';

  const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (prev !== body) {
    writeFileSync(OUT, body, 'utf8');
    console.log(`[gen-equipment-icons] wrote ${files.length} icons → ${OUT}`);
  } else {
    console.log(`[gen-equipment-icons] up to date (${files.length} icons)`);
  }
} catch (err) {
  console.warn('[gen-equipment-icons] non-fatal error, manifest left unchanged:', err && err.message);
  process.exit(0); // never break the build
}
